async (page) => {
  const scope = page.getByTestId('spectrum-plot');
  const figure = scope.getByRole('figure');
  const closeHelp = async () => { await page.getByRole('button', { name: 'Close plot help' }).click(); await page.getByRole('dialog', { name: 'Plot controls', exact: true, includeHidden: true }).waitFor({ state: 'detached' }); };
  const setThreshold = async (value) => { await page.getByRole('combobox', { name: 'Empty area threshold' }).click(); await page.getByRole('option', { name: value, exact: true }).click(); };
  const read = async (plot) => plot.evaluate(el => ({ x: [...el._fullLayout.xaxis.range], autoX: !!el._fullLayout.xaxis.autorange, autoY: !!el._fullLayout.yaxis.autorange }));
  await setThreshold('95%'); await closeHelp();
  const rect = await figure.locator('.nsewdrag').boundingBox();
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2);
  await page.mouse.wheel(rect.width * .9, 0);
  await page.waitForTimeout(1200);
  const tolerant = await read(figure);
  if (tolerant.autoX) throw new Error('95% setting did not retain the partial view');
  await scope.getByRole('button', { name: 'Plot controls' }).click();
  await setThreshold('75%'); await closeHelp();
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2);
  await page.mouse.wheel(1, 0);
  await page.waitForFunction(() => document.querySelector('[data-testid="spectrum-plot"] [role="figure"]')._fullLayout.xaxis.autorange, undefined, { timeout: 8000 });
  const sensitive = await read(figure);
  await scope.getByRole('button', { name: 'Plot controls' }).click();
  await page.getByRole('switch', { name: 'Auto-fit empty views' }).uncheck(); await closeHelp();
  await page.mouse.move(rect.x + rect.width / 2, rect.y + rect.height / 2);
  await page.mouse.wheel(rect.width * 4, 0); await page.waitForTimeout(1200);
  const disabled = await read(figure);
  if (disabled.autoX) throw new Error('Disabled protection still fitted');
  await scope.getByRole('button', { name: 'Enlarge chart: Frequency domain' }).click();
  const large = page.getByRole('dialog', { name: 'Frequency domain' });
  const largePlot = large.getByRole('figure', { name: 'Frequency domain' });
  await largePlot.locator('.nsewdrag').waitFor({ state: 'visible' });
  await large.getByRole('button', { name: 'Plot controls' }).click();
  const sharedDisabled = !(await page.getByRole('switch', { name: 'Auto-fit empty views' }).isChecked());
  if (!sharedDisabled) throw new Error('Enlarged view lost the per-chart setting');
  await page.getByRole('switch', { name: 'Auto-fit empty views' }).check(); await closeHelp();
  await page.waitForFunction(() => { const el = document.querySelector('[role="dialog"] [role="figure"]'); return el && el._fullLayout.xaxis.autorange && el._fullLayout.yaxis.autorange; }, undefined, { timeout: 8000 });
  const enlargedFit = await read(largePlot);
  await large.getByRole('button', { name: 'Close enlarged chart' }).click();
  await large.waitFor({ state: 'detached' });
  await figure.locator('.nsewdrag').waitFor({ state: 'visible' });
  await page.waitForFunction(() => document.querySelector('[data-testid="spectrum-plot"] [role="figure"]')._fullLayout.xaxis.autorange);
  return { tolerant, sensitive, disabled, sharedDisabled, enlargedFit, restoredInline: await read(figure) };
}
