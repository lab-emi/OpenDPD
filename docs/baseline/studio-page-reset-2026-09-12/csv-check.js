async (page) => {
  const base = page.url().split('/').slice(0,3).join('/');
  const check = (ok, message) => { if (!ok) throw new Error(message); };
  await page.goto(base+'/datasets');
  await page.getByRole('button',{name:'Create Your Own Dataset',exact:true}).click();
  const form = page.getByRole('dialog',{name:'Create Your Own Dataset',exact:true});
  await form.locator('input[type=file]').setInputFiles('/Users/gaochang/git/OpenDPD/datasets/MyCustomPA/data.csv');
  await form.getByRole('button',{name:'Continue',exact:true}).click();
  await form.getByLabel('Display name',{exact:true}).fill('Discard CSV draft');
  await form.getByRole('button',{name:'Reset page',exact:true}).click();
  const prompt=page.getByRole('dialog',{name:'Reset this page?',exact:true});
  await prompt.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByRole('dialog',{name:'Reset this page?',exact:true,includeHidden:true}).waitFor({state:'detached'});
  check(await form.getByLabel('Display name',{exact:true}).inputValue()==='Discard CSV draft','cancel lost CSV draft');
  await form.getByRole('button',{name:'Reset page',exact:true}).click();
  await prompt.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByRole('dialog',{name:'Reset this page?',exact:true,includeHidden:true}).waitFor({state:'detached'});
  await form.locator('#workflow-step-0[aria-selected="true"]').waitFor();
  check(!(await form.innerText()).includes('data.csv'),'CSV filename remains');
  check(await form.getByRole('button',{name:'Continue',exact:true}).isDisabled(),'CSV validation remains');
  await page.screenshot({path:'output/playwright/page-reset-csv-after.png',scale:'css'});
  await form.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByRole('dialog',{name:'Create Your Own Dataset',exact:true,includeHidden:true}).waitFor({state:'detached'});
  await page.getByRole('button',{name:'Reset Studio',exact:true}).click();
  await page.getByRole('dialog').getByRole('button',{name:'Reset',exact:true}).click();
  const guide=page.getByRole('dialog',{name:'Guided setup Create your first dataset',exact:true});
  await guide.waitFor();
  check(await guide.evaluate(el=>el.contains(document.activeElement)),'guide focus lost');
  await guide.getByRole('button',{name:'Skip tutorial',exact:true}).click();
  await page.getByRole('dialog',{name:'Guided setup Create your first dataset',exact:true,includeHidden:true}).waitFor({state:'detached'});
  await page.getByTestId('language-menu').click();
  await page.getByRole('menuitem',{name:'中文',exact:true}).click();
  await page.waitForFunction(()=>document.documentElement.lang==='zh-CN');
  await page.getByRole('menu',{includeHidden:true}).waitFor({state:'detached'});
  await page.getByRole('button',{name:'复原本页',exact:true}).click();
  await page.getByRole('dialog',{name:'复原当前页面？',exact:true}).waitFor();
  await page.screenshot({path:'output/playwright/page-reset-confirm-zh.png',scale:'css'});
  return {csv_cancel_preserved:true,csv_reset_cleared:true,global_guide_focus:true,chinese_confirmation:true};
}
